import type { ChartResult } from '@/lib/types';
import PanchangaGrid from './PanchangaGrid';
import PlanetTable from './PlanetTable';
import VargaExplorer from './VargaExplorer';
import DashaSection from './DashaSection';
import AspectsSection from './AspectsSection';
import CharaKarakasSection from './CharaKarakasSection';
import YogasSection from './YogasSection';
import AIInsightSection from './AIInsightSection';
import SarvashtakavargaSection from './SarvashtakavargaSection';
import TransitSection from './TransitSection';

interface ResultsViewProps {
  result: ChartResult;
  onReset: () => void;
}

const SIGNS_FULL = [
  'Aries', 'Taurus', 'Gemini', 'Cancer', 'Leo', 'Virgo',
  'Libra', 'Scorpio', 'Sagittarius', 'Capricorn', 'Aquarius', 'Pisces',
];

function generateTextReport(result: ChartResult): string {
  const r = result;
  const bi = r.birth_info;
  const lines: string[] = [];
  lines.push('═'.repeat(60));
  lines.push('VEDIC BIRTH CHART REPORT — VedicAstroCalc');
  lines.push('═'.repeat(60));
  lines.push('');
  lines.push(`Name        : ${bi.name}`);
  lines.push(`Birth Date  : ${bi.day}/${bi.month}/${bi.year}`);
  lines.push(`Birth Time  : ${String(bi.hour).padStart(2,'0')}:${String(bi.minute).padStart(2,'0')} (UTC${bi.time_offset >= 0 ? '+' : ''}${bi.time_offset})`);
  lines.push(`Location    : Lat ${bi.lat.toFixed(4)}, Lon ${bi.lon.toFixed(4)}`);
  lines.push(`Ayanamsa    : Lahiri ${r.ayanamsa.toFixed(4)}°`);
  lines.push(`Ascendant   : ${r.ascendant.sign_name} ${r.ascendant.degree.toFixed(2)}°`);
  lines.push(`              Nakshatra: ${r.ascendant.nakshatra} Pada ${r.ascendant.pada} (Lord: ${r.ascendant.nak_lord})`);
  lines.push(`Arudha Lagna: ${r.arudha_lagna.sign_name} (Lord: ${r.arudha_lagna.lagna_lord})`);
  if (r.arudha_lagna.exception_applied) {
    lines.push(`              [${r.arudha_lagna.exception_applied}]`);
  }
  lines.push('');
  lines.push('─'.repeat(60));
  lines.push('PANCHANGA');
  lines.push('─'.repeat(60));
  lines.push(`Vara      : ${r.panchanga.vara.name}`);
  lines.push(`Tithi     : ${r.panchanga.tithi.name} (${r.panchanga.tithi.paksha}) ${r.panchanga.tithi.completion}%`);
  lines.push(`Nakshatra : ${r.panchanga.nakshatra.name} Pada ${r.panchanga.nakshatra.pada} (Lord: ${r.panchanga.nakshatra.lord})`);
  lines.push(`Yoga      : ${r.panchanga.yoga.name}`);
  lines.push(`Karana    : ${r.panchanga.karana.name}`);
  lines.push('');
  lines.push('─'.repeat(60));
  lines.push('PLANETARY POSITIONS');
  lines.push('─'.repeat(60));
  for (const name of ['Sun','Moon','Mars','Mercury','Jupiter','Venus','Saturn','Rahu','Ketu']) {
    const p = r.planets[name];
    if (!p) continue;
    lines.push(
      `${name.padEnd(9)}: ${SIGNS_FULL[p.sign].padEnd(13)} H${p.house} | ${p.nakshatra} P${p.pada} | ${p.dignity}${p.is_retrograde ? ' (R)' : ''} | Avastha: ${p.avastha}`
    );
  }
  lines.push('');
  if (r.yogas.length > 0) {
    lines.push('─'.repeat(60));
    lines.push('ACTIVE YOGAS');
    lines.push('─'.repeat(60));
    for (const y of r.yogas) {
      lines.push(`• ${y.name} (${y.planets.join(', ')})`);
      lines.push(`  ${y.effect}`);
    }
    lines.push('');
  }
  lines.push('═'.repeat(60));
  lines.push('Generated by VedicAstroCalc · Astronomia VSOP87 · Lahiri Ayanamsa');
  lines.push('═'.repeat(60));
  return lines.join('\n');
}

export default function ResultsView({ result, onReset }: ResultsViewProps) {
  const { birth_info, ascendant, ayanamsa, arudha_lagna, yogas, panchanga } = result;

  function handleSave() {
    const text = generateTextReport(result);
    const blob = new Blob([text], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${birth_info.name.replace(/\s+/g, '_')}_vedic_chart.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }

  return (
    <div className="max-w-7xl mx-auto px-4 py-6 sm:py-10 animate-fade-in">
      {/* Back button */}
      <button
        onClick={onReset}
        className="btn-ghost flex items-center gap-2 px-4 py-2 rounded-xl text-sm mb-6"
      >
        <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
          <path d="M19 12H5M12 5l-7 7 7 7" strokeLinecap="round" strokeLinejoin="round" />
        </svg>
        Calculate New Chart
      </button>

      {/* Header card */}
      <div className="glass-card rounded-2xl p-6 mb-6">
        <div className="flex flex-col sm:flex-row sm:items-start justify-between gap-4">
          <div className="flex-1">
            <div className="flex items-center gap-3 mb-1">
              <div className="w-10 h-10 rounded-full bg-amber-50 border border-amber-200 flex items-center justify-center text-lg">
                🪐
              </div>
              <div>
                <h2
                  className="font-display text-2xl sm:text-3xl gold-shimmer"
                  style={{ fontFamily: 'Cinzel, serif' }}
                >
                  {birth_info.name}
                </h2>
                <p className="text-stone-500 text-sm font-body">
                  {birth_info.day}/{birth_info.month}/{birth_info.year} at{' '}
                  {String(birth_info.hour).padStart(2, '0')}:
                  {String(birth_info.minute).padStart(2, '0')}
                  {birth_info.isSriLanka && (
                    <span className="ml-2 text-stone-400">
                      🇱🇰 UTC+{birth_info.time_offset}
                    </span>
                  )}
                </p>
              </div>
            </div>
          </div>
          <button
            onClick={handleSave}
            className="btn-ghost flex items-center gap-2 px-4 py-2.5 rounded-xl text-sm flex-shrink-0"
          >
            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.5">
              <path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4M7 10l5 5 5-5M12 15V3" strokeLinecap="round" strokeLinejoin="round"/>
            </svg>
            Save Report
          </button>
        </div>

        <div className="mt-4 grid grid-cols-2 sm:grid-cols-4 gap-3">
          <div className="glass-card-darker rounded-xl p-3">
            <p className="text-xs text-stone-400 font-display uppercase tracking-wide mb-1">Ascendant</p>
            <p className="text-amber-700 font-semibold font-body">{ascendant.sign_name}</p>
            <p className="text-xs text-stone-500">{ascendant.degree.toFixed(2)}°</p>
          </div>
          <div className="glass-card-darker rounded-xl p-3">
            <p className="text-xs text-stone-400 font-display uppercase tracking-wide mb-1">Nakshatra</p>
            <p className="text-amber-700 font-semibold font-body text-sm">{ascendant.nakshatra}</p>
            <p className="text-xs text-stone-500">Pada {ascendant.pada} · {ascendant.nak_lord}</p>
          </div>
          <div className="glass-card-darker rounded-xl p-3">
            <p className="text-xs text-stone-400 font-display uppercase tracking-wide mb-1">Ayanamsa</p>
            <p className="text-amber-700 font-semibold font-body">{ayanamsa.toFixed(4)}°</p>
            <p className="text-xs text-stone-500">Lahiri (Sidereal)</p>
          </div>
          <div className="glass-card-darker rounded-xl p-3">
            <p className="text-xs text-stone-400 font-display uppercase tracking-wide mb-1">Coordinates</p>
            <p className="text-stone-700 font-body text-sm">{birth_info.lat.toFixed(4)}°N</p>
            <p className="text-xs text-stone-500">{birth_info.lon.toFixed(4)}°E</p>
          </div>
        </div>
      </div>

      {/* Panchanga */}
      <div className="glass-card rounded-2xl p-6 mb-6">
        <PanchangaGrid panchanga={panchanga} />
      </div>

      {/* Planet table */}
      <div className="glass-card rounded-2xl p-6 mb-6">
        <PlanetTable result={result} />
      </div>

      {/* Varga Explorer */}
      <div className="glass-card rounded-2xl p-6 mb-6">
        <VargaExplorer result={result} />
      </div>

      {/* Vimshottari Dasha */}
      <div className="glass-card rounded-2xl p-6 mb-6">
        <DashaSection result={result} />
      </div>

      {/* Chara Karakas + Graha Yuddha */}
      <div className="glass-card rounded-2xl p-6 mb-6">
        <CharaKarakasSection result={result} />
      </div>

      {/* Aspects */}
      <div className="glass-card rounded-2xl p-6 mb-6">
        <AspectsSection result={result} />
      </div>

      {/* Sarvashtakavarga */}
      <div className="glass-card rounded-2xl p-6 mb-6">
        <SarvashtakavargaSection result={result} />
      </div>

      {/* Current Transits */}
      <div className="glass-card rounded-2xl p-6 mb-6">
        <TransitSection result={result} />
      </div>

      {/* Yogas */}
      <div className="glass-card rounded-2xl p-6 mb-6">
        <YogasSection yogas={yogas} />
      </div>

      {/* AI Insight */}
      <div className="glass-card rounded-2xl p-6 mb-6">
        <AIInsightSection result={result} />
      </div>

      {/* Arudha Lagna footer note */}
      <div className="glass-card rounded-xl p-4 text-center">
        <p className="text-stone-500 text-sm font-body">
          <span className="text-amber-600 font-display text-xs uppercase tracking-widest mr-2">
            Arudha Lagna (AL):
          </span>
          {arudha_lagna.sign_name}
          {arudha_lagna.exception_applied && (
            <span className="ml-2 text-stone-400 text-xs italic">
              ({arudha_lagna.exception_applied})
            </span>
          )}
          <span className="mx-2 text-stone-300">·</span>
          Lord: {arudha_lagna.lagna_lord}
        </p>
      </div>
    </div>
  );
}
